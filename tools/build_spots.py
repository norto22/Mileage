#!/usr/bin/env python3
"""Builds Mileage's race spot routes from the game's West Coast route files.

    python3 tools/build_spots.py <level folder>          write both route lists
    python3 tools/build_spots.py --check <level folder>  exit non-zero if either is stale

<level folder> is the game's levels/west_coast_usa folder holding quickrace/<id>.json
(each route's checkpoint names, laps and whether it is a circuit) and
quickrace-prefabs/<id>.prefab and <id>_forward.prefab (where each checkpoint and the
standing start are). Every route except the drag strip is written, with the same data,
to two places:

  Resources/Server/Mileage/mileage.lua                         between its GENERATED SPOT
                                                                ROUTES markers
  Resources/Client/Mileage/lua/ge/extensions/mileage/spotRoutes.lua   the whole file

The server's copy lives inside mileage.lua because the server's updater and the release
package carry that one file. Checkpoints are in the game's order (lapConfig, then the
finish line, as scenario/quickRaceLoader.lua builds them); an open route is one lap.
Routes whose standing starts lie within SPOT_METRES share one spot. A missing checkpoint
or start stops the tool with the route's name. Needs only the Python 3 standard library.
"""
import argparse
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVER_PLUGIN = "Resources/Server/Mileage/mileage.lua"
CLIENT_ROUTES = "Resources/Client/Mileage/lua/ge/extensions/mileage/spotRoutes.lua"
BEGIN = "-- BEGIN GENERATED SPOT ROUTES\n"
END = "-- END GENERATED SPOT ROUTES"
SKIPPED = {"drag_race"}
SPOT_METRES = 5.0
JOIN_METRES = 4.5
# The barrier shapes that close a course, by file name: the local axis each one is long
# along and half its length in metres at scale 1. A shape whose long side is not known
# stands for a cross of both axes, so it closes the road whichever way it faces. The
# lengths are the measured spacing of each kind in its rows (3.2 m concrete, 1.9 m
# construction).
WALL_SHAPES = {
    "s_concrete_race_barrier.dae": ("x", 1.6),
    "constructionbarrier.dae": ("y", 0.95),
    "pole_fence2.dae": ("xy", 1.0),
    "ut_race_caution_tape_barricade_c_curve.dae": ("xy", 1.5),
}

HEADER = (
    "-- Generated by tools/build_spots.py from the game's West Coast route files; do not edit.\n"
    "-- One entry per route: spot groups the routes that share a standing start; checkpoints\n"
    "-- are in race order with the finish line last; grid is the standing start, dir the way\n"
    "-- it faces; length is the whole race in metres, straight between checkpoints.\n"
)
WALLS_NOTE = (
    "-- walls (this copy only) are the course's barriers as flat segments {x1, y1, x2, y2}.\n"
)


class BuildError(Exception):
    pass


def repo_path(rel):
    return os.path.join(ROOT, rel)


def read_text(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def read_route_file(path):
    """The route file as a dict; the game reads JSON with trailing commas."""
    text = re.sub(r",(\s*[\]}])", r"\1", read_text(path))
    try:
        return json.loads(text)
    except ValueError as err:
        raise BuildError(f"{os.path.basename(path)} does not read: {err}") from err


def numbers(text):
    return [float(part) for part in text.split()]


def prefab_objects(text, kind):
    """{name: {field: value}} for each `new <kind>(<name>) { ... };` in a prefab."""
    found = {}
    pattern = re.compile(r"new\s+" + kind + r"\((\w+)\)\s*\{(.*?)\};", re.S)
    for match in pattern.finditer(text):
        fields = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', match.group(2)))
        found[match.group(1)] = fields
    return found


def statics(text):
    """The fields of each `new TSStatic() { ... };` in a prefab."""
    return [dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', body))
            for body in re.findall(r"new\s+TSStatic\([^)]*\)\s*\{(.*?)\};", text, re.S)]


def axes(fields):
    """The object's flat X and Y axes. A prefab gives its rotation as `rotationMatrix` (the
    axes one after another) or as `rotation` (an axis and an angle in degrees)."""
    if "rotationMatrix" in fields:
        m = numbers(fields["rotationMatrix"])
        return (m[0], m[1]), (m[3], m[4])
    ax, ay, az, degrees = (numbers(fields.get("rotation", "0 0 1 0")) + [0, 0, 1, 0])[:4]
    norm = math.sqrt(ax * ax + ay * ay + az * az) or 1.0
    ax, ay, az = ax / norm, ay / norm, az / norm
    c, s = math.cos(math.radians(degrees)), math.sin(math.radians(degrees))
    x_axis = (c + ax * ax * (1 - c), ay * ax * (1 - c) + az * s)
    y_axis = (ax * ay * (1 - c) - az * s, c + ay * ay * (1 - c))
    return x_axis, y_axis


def flat_unit(v):
    norm = math.hypot(v[0], v[1])
    return (v[0] / norm, v[1] / norm) if norm > 1e-6 else None


def walls_of(texts):
    """The walls of a course from its prefabs' barriers: a piece per barrier and a join
    between each pair within JOIN_METRES, each a flat segment, in a stable order."""
    barriers = []
    for text in texts:
        for fields in statics(text):
            shape = fields.get("shapeName", "").replace("\\", "/").split("/")[-1].lower()
            if shape not in WALL_SHAPES or "position" not in fields:
                continue
            long_axis, half = WALL_SHAPES[shape]
            scale = (numbers(fields.get("scale", "1 1 1")) + [1, 1, 1])[:3]
            x_axis, y_axis = axes(fields)
            pos = numbers(fields["position"])[:2]
            pieces = []
            for name, axis, size in (("x", x_axis, scale[0]), ("y", y_axis, scale[1])):
                unit = flat_unit(axis)
                if name in long_axis and unit:
                    length = half * abs(size)
                    pieces.append((pos[0] - unit[0] * length, pos[1] - unit[1] * length,
                                   pos[0] + unit[0] * length, pos[1] + unit[1] * length))
            barriers.append((pos, pieces))
    segments = set()
    for _, pieces in barriers:
        segments.update(pieces)
    for i, (a, _) in enumerate(barriers):
        for b, _ in barriers[i + 1:]:
            if 0 < math.hypot(a[0] - b[0], a[1] - b[1]) <= JOIN_METRES:
                segments.add((a[0], a[1], b[0], b[1]))
    rounded = {tuple(round(v, 1) for v in seg) for seg in segments}
    return sorted(seg for seg in rounded if (seg[0], seg[1]) != (seg[2], seg[3]))


def words(route_id):
    return " ".join(part.capitalize() for part in route_id.split("_"))


def distance(a, b):
    return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(3)))


def facing(spawn, route_id):
    """The way a car placed at the spawn faces, a flat unit vector. The game sets the car's
    rotation to the spawn's, and a car faces along its own -Y. A prefab gives the rotation
    as `rotationMatrix` (its axes one after another, so the second three numbers are the
    object's Y) or as `rotation` (an axis and an angle in degrees)."""
    if "rotationMatrix" in spawn:
        y_axis = numbers(spawn["rotationMatrix"])[3:6]
    else:
        ax, ay, az, degrees = (numbers(spawn.get("rotation", "0 0 1 0")) + [0, 0, 1, 0])[:4]
        norm = math.sqrt(ax * ax + ay * ay + az * az) or 1.0
        ax, ay, az = ax / norm, ay / norm, az / norm
        c, s = math.cos(math.radians(degrees)), math.sin(math.radians(degrees))
        # The rotation applied to (0, 1, 0) (Rodrigues' formula).
        y_axis = [ax * ay * (1 - c) - az * s, c + ay * ay * (1 - c), ay * az * (1 - c) + ax * s]
    flat = [-y_axis[0], -y_axis[1]]
    norm = math.hypot(*flat)
    if norm < 1e-6:
        raise BuildError(f"{route_id}: the standing start faces straight up or down")
    return [flat[0] / norm, flat[1] / norm, 0.0]


def read_route(level, route_id):
    spec = read_route_file(os.path.join(level, "quickrace", route_id + ".json"))
    prefabs = os.path.join(level, "quickrace-prefabs")
    waypoints, spawns, texts = {}, {}, []
    for name in (route_id + ".prefab", route_id + "_forward.prefab"):
        path = os.path.join(prefabs, name)
        if os.path.exists(path):
            text = read_text(path)
            texts.append(text)
            waypoints.update(prefab_objects(text, "BeamNGWaypoint"))
            spawns.update(prefab_objects(text, "SpawnSphere"))
    # A route without a finish line (highway_race) ends at its last lap checkpoint, as the
    # game's loader appends nothing for it.
    finish = spec.get("finishLineCheckpoint")
    order = list(spec.get("lapConfig") or []) + ([finish] if finish else [])
    if not order:
        raise BuildError(f"{route_id}: its route file names no checkpoints")
    checkpoints = []
    for name in order:
        fields = waypoints.get(name)
        if not fields or "position" not in fields:
            raise BuildError(f"{route_id}: checkpoint {name} is not in its route files")
        scale = numbers(fields.get("scale", "8 8 8"))
        checkpoints.append({"pos": numbers(fields["position"]), "r": scale[0]})
    spawn = spawns.get(route_id + "_standing_spawn")
    if not spawn or "position" not in spawn:
        raise BuildError(f"{route_id}: the standing start is not in its route files")
    forward = facing(spawn, route_id)
    closed = spec.get("closed") is True
    laps = int(spec.get("lapCount") or 1) if closed else 1
    start = numbers(spawn["position"])
    # The first lap starts from the grid; every later lap from the finish line.
    first = distance(start, checkpoints[0]["pos"])
    path = sum(distance(checkpoints[i]["pos"], checkpoints[i + 1]["pos"]) for i in range(len(checkpoints) - 1))
    again = distance(checkpoints[-1]["pos"], checkpoints[0]["pos"])
    length = first + path + (laps - 1) * (again + path)
    return {
        "id": route_id, "name": words(route_id), "closed": closed, "laps": laps,
        "grid": {"pos": start, "dir": forward}, "checkpoints": checkpoints, "length": length,
        "walls": walls_of(texts),
    }


def read_routes(level):
    folder = os.path.join(level, "quickrace")
    if not os.path.isdir(folder):
        raise BuildError(f"no quickrace folder in {level}")
    ids = sorted(name[:-5] for name in os.listdir(folder) if name.endswith(".json"))
    routes = [read_route(level, route_id) for route_id in ids if route_id not in SKIPPED]
    if not routes:
        raise BuildError(f"no routes in {folder}")
    # A spot is named after the first route (by id) standing at its start.
    for route in routes:
        route["spot"] = next(other["id"] for other in routes
                             if distance(other["grid"]["pos"], route["grid"]["pos"]) <= SPOT_METRES)
    return routes


def num(value, places):
    text = f"{value:.{places}f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def point(values, places):
    return "{x = %s, y = %s, z = %s}" % tuple(num(v, places) for v in values)


WALLS_PER_LINE = 6


def lua_routes(routes, walls=False):
    """The route list as a Lua table constructor, one route per block; with walls, each
    route's walls too (the game's copy only)."""
    lines = ["{"]
    for route in routes:
        lines.append("\t{id = %s, spot = %s, name = %s, closed = %s, laps = %d, length = %s," % (
            json.dumps(route["id"]), json.dumps(route["spot"]), json.dumps(route["name"]),
            "true" if route["closed"] else "false", route["laps"], num(route["length"], 0)))
        lines.append("\t\tgrid = {pos = %s, dir = %s}," % (point(route["grid"]["pos"], 3),
            point(route["grid"]["dir"], 4)))
        lines.append("\t\tcheckpoints = {")
        for cp in route["checkpoints"]:
            lines.append("\t\t\t{pos = %s, r = %s}," % (point(cp["pos"], 3), num(cp["r"], 2)))
        if walls and route["walls"]:
            lines.append("\t\t},")
            lines.append("\t\twalls = {")
            segs = ["{%s}," % ", ".join(num(v, 1) for v in seg) for seg in route["walls"]]
            for i in range(0, len(segs), WALLS_PER_LINE):
                lines.append("\t\t\t" + " ".join(segs[i:i + WALLS_PER_LINE]))
        lines.append("\t\t}},")
    lines.append("}")
    return "\n".join(lines)


def server_block(routes):
    return HEADER + "local SPOT_ROUTES = " + lua_routes(routes) + "\n"


def client_file(routes):
    return ("--Mileage :: race spot routes (CLIENT)\n--\n" + HEADER + WALLS_NOTE + "\nlocal M = {}\n\nM.routes = "
            + lua_routes(routes, walls=True) + "\n\nreturn M\n")


def with_server_block(plugin, block):
    start = plugin.find(BEGIN)
    end = plugin.find(END)
    if start < 0 or end < start:
        raise BuildError(f"{SERVER_PLUGIN} has no GENERATED SPOT ROUTES markers")
    return plugin[:start + len(BEGIN)] + block + plugin[end:]


def main():
    parser = argparse.ArgumentParser(description="Build Mileage's race spot routes from the game's route files.")
    parser.add_argument("--check", action="store_true", help="exit non-zero if either route list is stale")
    parser.add_argument("level", help="the game's levels/west_coast_usa folder")
    args = parser.parse_args()
    try:
        routes = read_routes(args.level)
        plugin = read_text(repo_path(SERVER_PLUGIN))
        wanted_plugin = with_server_block(plugin, server_block(routes))
        wanted_client = client_file(routes)
        spots = len({route["spot"] for route in routes})
        if args.check:
            current_client = read_text(repo_path(CLIENT_ROUTES)) if os.path.exists(repo_path(CLIENT_ROUTES)) else ""
            stale = [path for path, now, wanted in ((SERVER_PLUGIN, plugin, wanted_plugin),
                                                   (CLIENT_ROUTES, current_client, wanted_client)) if now != wanted]
            if stale:
                for path in stale:
                    print(f"{path} differs from the route files; run python3 tools/build_spots.py {args.level}")
                return 1
            print(f"routes match: {len(routes)} routes in {spots} spots")
            return 0
        with open(repo_path(SERVER_PLUGIN), "w", encoding="utf-8", newline="\n") as f:
            f.write(wanted_plugin)
        with open(repo_path(CLIENT_ROUTES), "w", encoding="utf-8", newline="\n") as f:
            f.write(wanted_client)
        print(f"wrote {len(routes)} routes in {spots} spots")
        return 0
    except (BuildError, OSError) as err:
        print(f"build_spots: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
